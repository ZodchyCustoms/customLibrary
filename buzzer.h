// This use Timer_0 and OCR0A
// sounds only 7 notes, use Timer_0
class Buzzer
{
public:
  Buzzer(uint8_t pin)
  {
    this->_pin = pin;
    setPin(_pin);
    pinWrite(_pin, _pinState);
    TCCR0A = 0;
    TCCR0B = 0;
    TCCR0A |= (1 << WGM01);     // CTC mode
    off();
  }

  void playNote(uint8_t note)
  {
    _duration_mode = false;
    _duration_state = false;
    _on(note);
  }
 
  void playNote(uint8_t note, uint16_t duration)
  {
    _duration_state = true;
    _duration_mode = true;
    _ticks = (duration * 10 / _tickDuration[note]);
    _on(note);
  }

  void off()
  {
    _duration_state = false;
    _duration_mode = false;
    TIMSK0 = 0;
    TCNT0 = 0;
    TIFR0 = 0;
  }
  
  void meandrTick()
  {
    switch (_duration_mode)
    {
      case true:
      switch (_duration_state)
      {
        case true:
        pinWrite(_pin, _pinState ^= 1);
        _ticks < 2 ? _duration_state = false : _ticks--;
        break;
        case false:
        off();
        break;
      }
      break;
      case false:
      pinWrite(_pin, _pinState ^= 1);
      break;
    }
  }

  
  private:

  void _on(uint8_t noteIndex)
  {
    TCCR0B = PRESCALLER_T0;
    TIMSK0 |= (1 << OCIE0A);
    OCR0A = _notes[noteIndex];
  }

  volatile bool _pinState = false, _duration_state = false, _duration_mode = false;
  uint8_t _pin;
  volatile uint16_t _ticks = 0;
  const uint8_t _notes[7] = { 118, 105, 93, 88, 78, 70, 62 };
  const uint8_t _tickDuration[7] = { 19, 17, 15, 14, 12, 11, 10 };   // x10 - for use without float
  
};









